"use client";

import QRCode from "qrcode";
import { useEffect, useState } from "react";
import { cn } from "@/lib/utils";

/** Inline SVG QR code (generated locally, never sent to a third-party service). */
export function QrCode({ value, label, className }: { value: string; label: string; className?: string }) {
  const [svg, setSvg] = useState<string | null>(null);

  useEffect(() => {
    let alive = true;
    QRCode.toString(value, { type: "svg", margin: 0, errorCorrectionLevel: "M", color: { dark: "#14201C", light: "#FFFFFF" } })
      .then((s) => alive && setSvg(s))
      .catch(() => alive && setSvg(null));
    return () => {
      alive = false;
    };
  }, [value]);

  return (
    <span
      role="img"
      aria-label={label}
      className={cn("block bg-white [&>svg]:block [&>svg]:size-full", className)}
      // Generated by the qrcode library from our own URL.
      dangerouslySetInnerHTML={svg ? { __html: svg } : undefined}
    />
  );
}

/** Absolute URL a label points to. Uses NEXT_PUBLIC_SITE_URL so labels printed from a preview build still open production. */
export function labelUrl(locationId: string) {
  const base = process.env.NEXT_PUBLIC_SITE_URL || window.location.origin;
  return `${base.replace(/\/$/, "")}/l/${locationId}`;
}
